"""Bounded SQL probes extending the validated 22-query experimental selection."""
from variants import Variant, targeted


def prepare_frame(spark, candidate):
    frame = spark.sql(candidate.sql)
    if candidate.name in ('single_scan_quantity_state', 'single_scan_filtered_orders'):
        # Preserve the original unaliased aggregate's public schema metadata.
        frame = frame.withMetadata('sum(l_quantity)', {'__autoGeneratedAlias': 'true'})
    return frame


def cases():
    q3 = """WITH line_revenue AS (
        SELECT l_orderkey, SUM(l_extendedprice * (1 - l_discount)) AS probe_revenue
        FROM lineitem WHERE l_shipdate > DATE '1995-03-15' GROUP BY l_orderkey)
        SELECT l_orderkey, SUM(probe_revenue) AS revenue, o_orderdate, o_shippriority
        FROM customer JOIN orders ON c_custkey = o_custkey
        JOIN line_revenue ON l_orderkey = o_orderkey
        WHERE c_mktsegment = 'BUILDING' AND o_orderdate < DATE '1995-03-15'
        GROUP BY l_orderkey, o_orderdate, o_shippriority
        ORDER BY revenue DESC, o_orderdate LIMIT 10"""
    q10 = """WITH fact_revenue AS (
        SELECT o_custkey, SUM(l_extendedprice * (1 - l_discount)) AS probe_revenue
        FROM orders JOIN lineitem ON l_orderkey = o_orderkey
        WHERE o_orderdate >= DATE '1993-10-01'
          AND o_orderdate < DATE '1993-10-01' + INTERVAL '3' MONTH
          AND l_returnflag = 'R' GROUP BY o_custkey)
        SELECT c_custkey, c_name, SUM(probe_revenue) AS revenue, c_acctbal,
            n_name, c_address, c_phone, c_comment
        FROM fact_revenue JOIN customer ON c_custkey = o_custkey
        JOIN nation ON c_nationkey = n_nationkey
        GROUP BY c_custkey, c_name, c_acctbal, c_phone, n_name, c_address, c_comment
        ORDER BY revenue DESC LIMIT 20"""
    q18 = """WITH line_quantity AS (
        SELECT l_orderkey, SUM(l_quantity) AS probe_quantity
        FROM lineitem GROUP BY l_orderkey HAVING SUM(l_quantity) > 300)
        SELECT /*+ BROADCAST(line_quantity) */ c_name, c_custkey, o_orderkey,
            o_orderdate, o_totalprice,
            CAST(SUM(probe_quantity) AS DECIMAL(25,2)) AS `sum(l_quantity)`
        FROM customer JOIN orders ON c_custkey = o_custkey
        JOIN line_quantity ON o_orderkey = l_orderkey
        GROUP BY c_name, c_custkey, o_orderkey, o_orderdate, o_totalprice
        ORDER BY o_totalprice DESC, o_orderdate LIMIT 100"""
    q9 = targeted(9).sql.replace("WHERE p_name LIKE '%green%')",
                                "WHERE p_name LIKE '%green%' AND p_partkey IS NOT NULL)")
    assert q9 != targeted(9).sql
    return [
        Variant(3, 'preaggregate_line_revenue', q3,
                'Reduce join input to one revenue state per order; retain duplicate dimension multiplicities',
                evidence='A GPU sum by l_orderkey executes below the fact join'),
        Variant(9, 'prefilter_partsupp_reuse', q9,
                'Align null rejection so the selective part-key broadcast can be shared',
                evidence='One part scan, reused exchange and a GPU semi join filtering partsupp'),
        Variant(10, 'preaggregate_customer_revenue', q10,
                'Aggregate fact revenue before attaching customer string payloads',
                evidence='GPU sum by o_custkey executes before the customer join'),
        Variant(18, 'single_scan_quantity_state', q18,
                'Use grouped quantity both for membership and final sum, removing the second fact scan',
                evidence='One lineitem scan and a broadcast of qualifying grouped quantity state')]


def refinements():
    q3 = cases()[0].sql.replace('SELECT l_orderkey, SUM(probe_revenue)',
        'SELECT /*+ BROADCAST(customer) */ l_orderkey, SUM(probe_revenue)')
    q18 = """WITH line_quantity AS (
        SELECT l_orderkey, SUM(l_quantity) AS probe_quantity
        FROM lineitem GROUP BY l_orderkey HAVING SUM(l_quantity) > 300),
        filtered_orders AS (
        SELECT /*+ BROADCAST(line_quantity) */ o_custkey, o_orderkey, o_orderdate,
            o_totalprice, probe_quantity
        FROM orders JOIN line_quantity ON o_orderkey = l_orderkey)
        SELECT /*+ BROADCAST(filtered_orders) */ c_name, c_custkey, o_orderkey,
            o_orderdate, o_totalprice,
            CAST(SUM(probe_quantity) AS DECIMAL(25,2)) AS `sum(l_quantity)`
        FROM customer JOIN filtered_orders ON c_custkey = o_custkey
        GROUP BY c_name, c_custkey, o_orderkey, o_orderdate, o_totalprice
        ORDER BY o_totalprice DESC, o_orderdate LIMIT 100"""
    return [
        Variant(3, 'preaggregate_broadcast_customer', q3,
                'Combine narrow per-order revenue state with a customer-key broadcast',
                evidence='GPU sum by l_orderkey and a customer-key GPU broadcast join'),
        Variant(18, 'single_scan_filtered_orders', q18,
                'Apply qualifying quantity state to orders before attaching customer payloads',
                evidence='One lineitem scan; grouped quantity and filtered orders both use GPU broadcast')]
